#!/usr/bin/env node
// Writes the Vietnamese page of the public site from the English one, so each language has an
// address of its own for search engines: site/index.html (the source) + site-vi.json → site/vi/index.html.
// Every element with a data-t key gets that key's Vietnamese text; the head (language, title,
// description, addresses) is rewritten too. `npm run deploy:site` runs this first.
//   node scripts/build-site.mjs           write the file
//   node scripts/build-site.mjs --check   exit 1 if it is out of date or a key has no translation
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://chorus-cli.web.app';
const en = readFileSync(path.join(root, 'site', 'index.html'), 'utf8');
const vi = JSON.parse(readFileSync(path.join(root, 'site-vi.json'), 'utf8'));
const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

const missing = [];
// An element with a key never contains another element of its own kind, so its end is the next closing tag.
let html = en.replace(/(<(\w+)\b[^>]*\bdata-t="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g, (all, open, _tag, key, _text, close) => {
  if (vi[key] === undefined) { missing.push(key); return all; }
  return `${open}${vi[key]}${close}`;
});
const [, title] = /<title>(.*?)<\/title>/.exec(en);
const [, description] = /<meta name="description" content="(.*?)">/.exec(en);
html = html
  .replace('<html lang="en">', '<html lang="vi">')
  .replace(/<!-- The public page[\s\S]*?-->/, '<!-- Generated by scripts/build-site.mjs from site/index.html and site-vi.json: edit those, not this file. -->')
  .replaceAll(title, attr(vi._title))
  .replaceAll(description, attr(vi._description))
  .replace(`<link rel="canonical" href="${SITE}/">`, `<link rel="canonical" href="${SITE}/vi">`)
  .replace(`<meta property="og:url" content="${SITE}/">`, `<meta property="og:url" content="${SITE}/vi">`)
  .replace('"url": "' + SITE + '/"', '"url": "' + SITE + '/vi"')
  .replace('content="en_US"', 'content="vi_VN"')
  .replace('<a href="/" hreflang="en" lang="en" aria-current="true">', '<a href="/" hreflang="en" lang="en">')
  .replace('<a href="/vi" hreflang="vi" lang="vi">', '<a href="/vi" hreflang="vi" lang="vi" aria-current="true">')
  .replaceAll('data-copy data-copied="Copied">Copy<', `data-copy data-copied="${attr(vi._copied)}">${vi._copy}<`)
  .replaceAll('href="#install"', 'href="#install"');

if (missing.length) {
  console.error(`✗ site-vi.json has no text for: ${missing.join(', ')}`);
  process.exit(1);
}
const out = path.join(root, 'site', 'vi', 'index.html');
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(out, 'utf8'); } catch { /* not written yet */ }
  if (now !== html) { console.error('✗ site/vi/index.html is out of date: run node scripts/build-site.mjs'); process.exit(1); }
  console.log('site/vi/index.html is up to date');
} else {
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, html);
  console.log(`wrote ${path.relative(root, out)}`);
}
